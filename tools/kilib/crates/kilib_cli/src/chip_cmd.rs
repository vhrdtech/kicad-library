//! `kilib model chip` and `kilib footprint chip`: the STEP models and the footprints of [`kilib::chip`]'s tables.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use anstream::{eprintln, println};
use clap::ValueHint;
use kilib::chip::footprint::{self, Outcome};
use kilib::chip::{self, Tables};
use kilib::{config, step};

use crate::{ConfigArgs, DIM, GREEN, RED, StockArgs, YELLOW, library_or_cwd};

#[derive(clap::Subcommand)]
pub enum ModelCommand {
    /// STEP models of the chip passives and power inductors of generate/*.toml
    ///
    /// One model per size and height of generate/chip-passives.toml and generate/power-inductors.toml, as
    /// OUT/VHRD_<Lib>.3dshapes/<footprint>.step: the body and its terminations as coloured solids, on z = 0,
    /// centred on the footprint origin. OUT is ${VHRD_3DMODEL_DIR}/generated by default (the variable from the
    /// environment or KiCad's config). Without --write it lists what it would write.
    #[command(after_help = "\
Examples:
  kilib model chip                                  what would be written into ${VHRD_3DMODEL_DIR}/generated
  kilib model chip --write
  kilib model chip --write --out /tmp/models C_0805_2012Metric_H1.25")]
    Chip {
        /// Only these parts (footprint names); default: all
        #[arg(value_name = "NAME")]
        names: Vec<String>,
        /// The models folder (default: ${VHRD_3DMODEL_DIR}/generated)
        #[arg(long, value_name = "DIR", value_hint = ValueHint::DirPath)]
        out: Option<PathBuf>,
        /// The kicad-library checkout with generate/ (default: the one around the current folder)
        #[arg(long, value_name = "DIR", value_hint = ValueHint::DirPath)]
        library: Option<PathBuf>,
        /// Write the models (an existing file is overwritten when it differs)
        #[arg(long)]
        write: bool,
        #[command(flatten)]
        config: ConfigArgs,
    },
}

impl ModelCommand {
    pub fn usage(&self) -> (&'static str, Vec<(&'static str, bool)>) {
        match self {
            ModelCommand::Chip { names, out, library, write, .. } => (
                "model chip",
                vec![
                    ("write", *write),
                    ("names", !names.is_empty()),
                    ("out", out.is_some()),
                    ("library", library.is_some()),
                ],
            ),
        }
    }
}

pub fn run(cmd: ModelCommand) -> Result<ExitCode, String> {
    let ModelCommand::Chip { names, out, library, write, config } = cmd;
    let library = library_or_cwd(library)?;
    let out = match out {
        Some(o) => o,
        None => {
            let vars = config::vars(config.dir().as_deref(), std::env::vars(), None)?;
            let dir = vars.get("VHRD_3DMODEL_DIR").ok_or("VHRD_3DMODEL_DIR is not set: pass --out DIR")?;
            Path::new(dir).join(chip::MODEL_SUBDIR)
        }
    };
    let parts = selected(Tables::load(&library)?.parts()?, &names)?;
    let (mut changed, mut same) = (0, 0);
    for part in &parts {
        let text = step::write(&part.name, &chip::model(part))?;
        let path = part.model_path(&out);
        if std::fs::read_to_string(&path).is_ok_and(|old| old == text) {
            same += 1;
            continue;
        }
        changed += 1;
        if write {
            std::fs::create_dir_all(path.parent().expect("a parent"))
                .map_err(|e| format!("{}: {e}", path.display()))?;
            std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
            println!("{GREEN}wrote{GREEN:#} {}", path.display());
        } else {
            println!("would write {}", path.display());
        }
    }
    println!(
        "{DIM}{changed} {} {}, {same} as they are{DIM:#}",
        if changed == 1 { "model" } else { "models" },
        if write { "written" } else { "to write" }
    );
    Ok(if write || changed == 0 { ExitCode::SUCCESS } else { ExitCode::from(1) })
}

#[derive(clap::Subcommand)]
pub enum FootprintCommand {
    /// Footprints of the chip passives and power inductors of generate/*.toml, one per size and height
    ///
    /// A chip part (C_0805_2012Metric_H1.25) is its size's base footprint (C_0805_2012Metric: the checkout's copy,
    /// else a fresh import of KiCad's stock one) under the new name, its description naming the body and height
    /// and its 3D model at ${VHRD_3DMODEL_DIR}/generated/ (`kilib model chip`); pads and drawing stay the base's.
    /// A power inductor (L_Shielded_4.0x4.0mm_H2.0) is drawn from its row: the maker's land, the body on the fab
    /// layer, then the fixes of `kilib lint` and the designator and Value of `kilib designators`; a current-sense
    /// resistor (R_Shunt_1206_3216Metric_H0.6_Pad2.80x1.84mm_Gap0.60mm) the same way. Only new files
    /// are written; one that differs from what would be made is reported. Without --write it lists what it would
    /// write and exits 1 when anything would.
    #[command(after_help = "\
Examples:
  kilib footprint chip
  kilib footprint chip --write
  kilib footprint chip --write --stock-dir ~/kicad-footprints C_0805_2012Metric_H1.25")]
    Chip {
        /// Only these parts (footprint names); default: all
        #[arg(value_name = "NAME")]
        names: Vec<String>,
        /// Write the new footprints
        #[arg(long)]
        write: bool,
        #[command(flatten)]
        stock: StockArgs,
    },
    /// The current-sense resistor lands of generate/current-sense.toml, computed, one line per row and height
    ///
    /// Each [[shunt]] row's IPC-7351B nominal land from its body and terminations, as the footprint that takes it
    /// has it (rows of one size within 0.05 mm share a land), next to the maker's recommended land. Only reads.
    #[command(after_help = "\
Examples:
  kilib footprint shunts")]
    Shunts {
        /// The kicad-library checkout with generate/ (default: the one around the current folder)
        #[arg(long, value_name = "DIR", value_hint = ValueHint::DirPath)]
        library: Option<PathBuf>,
    },
}

impl FootprintCommand {
    pub fn usage(&self) -> (&'static str, Vec<(&'static str, bool)>) {
        match self {
            FootprintCommand::Shunts { library } => ("footprint shunts", vec![("library", library.is_some())]),
            FootprintCommand::Chip { names, write, stock } => (
                "footprint chip",
                vec![
                    ("write", *write),
                    ("names", !names.is_empty()),
                    ("stock-dir", stock.stock_dir.is_some()),
                    ("library", stock.library.is_some()),
                ],
            ),
        }
    }
}

fn selected(parts: Vec<chip::Part>, names: &[String]) -> Result<Vec<chip::Part>, String> {
    let unknown: Vec<&str> =
        names.iter().filter(|n| !parts.iter().any(|p| &p.name == *n)).map(String::as_str).collect();
    if !unknown.is_empty() {
        return Err(format!("not in generate/*.toml: {}", unknown.join(", ")));
    }
    Ok(parts.into_iter().filter(|p| names.is_empty() || names.contains(&p.name)).collect())
}

pub fn run_footprints(cmd: FootprintCommand) -> Result<ExitCode, String> {
    let (names, write, stock) = match cmd {
        FootprintCommand::Chip { names, write, stock } => (names, write, stock),
        FootprintCommand::Shunts { library } => return shunts(library),
    };
    let library = library_or_cwd(stock.library.clone())?;
    let parts = selected(Tables::load(&library)?.parts()?, &names)?;
    let stock_dir = stock.stock_dir().ok();
    let items = footprint::plan(&library, stock_dir.as_deref(), &parts);
    let (mut new, mut same, mut differs, mut errors) = (0, 0, 0, 0);
    for i in &items {
        match &i.outcome {
            Outcome::New(_) => {
                new += 1;
                println!("{} {}", if write { "writes" } else { "would write" }, i.path.display());
            }
            Outcome::Same => same += 1,
            Outcome::Differs => {
                differs += 1;
                println!("{YELLOW}differs{YELLOW:#} {} (left as it is)", i.path.display());
            }
            Outcome::Error(e) => {
                errors += 1;
                eprintln!("{RED}error:{RED:#} {}: {e}", i.name);
            }
        }
    }
    if write && errors == 0 {
        footprint::apply(&items)?;
    }
    println!("{DIM}{new} new, {same} as they are, {differs} differ, {errors} errors{DIM:#}");
    if errors > 0 && stock_dir.is_none() {
        eprintln!("{DIM}no stock footprint folder: pass --stock-dir DIR for bases the checkout lacks{DIM:#}");
    }
    Ok(if errors > 0 || (!write && new > 0) { ExitCode::from(1) } else { ExitCode::SUCCESS })
}

/// `kilib footprint shunts`: the computed lands, one line per row and height.
fn shunts(library: Option<PathBuf>) -> Result<ExitCode, String> {
    let library = library_or_cwd(library)?;
    let tables = Tables::load(&library)?;
    println!(
        "{:<36} {:<5} {:<14} {:>6} {:>13} {:>5} {:>5}  {:<22} footprint",
        "series", "size", "range", "height", "pad", "gap", "span", "maker's pad / gap / span"
    );
    let mut footprints = 0;
    for (name, h, p) in chip::shunt::parts(&tables.shunt)? {
        footprints += 1;
        let land = &p.land;
        for r in p.rows_of(h) {
            let maker = r.maker_land.as_ref().map_or(String::new(), |m| {
                format!("{:.2}x{:.2} / {:.2} / {:.2}", m.pad_length, m.pad_width, m.gap, 2.0 * m.pad_length + m.gap)
            });
            println!(
                "{:<36} {:<5} {:<14} {:>6} {:>13} {:>5.2} {:>5.2}  {:<22} {DIM}{name}{DIM:#}",
                r.series.join(", "),
                r.size,
                r.range,
                chip::mm(h),
                format!("{:.3}x{:.2}", land.pad_length(), land.width),
                land.gap,
                land.span,
                maker,
            );
        }
    }
    println!("{DIM}{} rows, {footprints} footprints{DIM:#}", tables.shunt.len());
    Ok(ExitCode::SUCCESS)
}
